"""Rebuild work/index.js, the list behind the homepage's selected builds and the Work page.

The builds, their links, names and one-line descriptions come from the four landing pages
(builds/*/index.html): featured tiles first, then the All rows, in page order. Two things live in
work/index.json and are edited by hand or by the daily routine:
  selected  the repos shown on the homepage, in order (Pranav chooses these)
  results   one short measured result per repo, written from its demo page ("GO, 25 of 25 calls")
Each build's preview image is work/index/<repo>.jpg (800x500); a build without one shows text only.

    python3 scripts/build_index.py          # writes work/index.js, fails on any missing result
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATS = ["evals", "go-live-gates", "rollout-readiness", "agents"]
TILE = re.compile(r'<a class="tile[^"]*"(?: data-repo="([^"]+)")? href="([^"]+)">.*?<b>([^<]+)</b>.*?</span></span><span>(.*?)</span></span>', re.S)
ROW = re.compile(r'<li data-repo="([^"]+)"><a href="([^"]+)"><b>([^<]+)</b><em>([^<]*)</em>')


def main() -> int:
    src = json.loads((ROOT / "work/index.json").read_text())
    builds, seen = [], set()
    for cat in CATS:
        page = (ROOT / f"builds/{cat}/index.html").read_text()
        found = [(m.group(1) or m.group(2).rstrip("/").split("/")[-1], m.group(2), m.group(3), re.sub("<[^>]+>", "", m.group(4))) for m in TILE.finditer(page)]
        found += [m.groups() for m in ROW.finditer(page)]
        for repo, href, name, desc in found:
            if repo in seen:
                continue
            seen.add(repo)
            code = "github.com/" in href
            thumb = f"work/index/{repo}.jpg"
            builds.append({
                "repo": repo, "href": href, "name": html.unescape(name), "desc": html.unescape(desc), "cat": cat,
                "result": src["results"].get(repo),
                "code": code,
                "thumb": None if code or not (ROOT / thumb).exists() else thumb,
            })
    missing = [b["repo"] for b in builds if not b["result"]]
    unknown = [r for r in src["selected"] if r not in seen]
    if missing or unknown:
        print("missing results:", missing, "| selected but not on a landing page:", unknown)
        return 1
    out = {"selected": src["selected"], "builds": builds}
    (ROOT / "work/index.js").write_text("// Generated by scripts/build_index.py from the landing pages and work/index.json. Do not edit.\nwindow.BUILDS = " + json.dumps(out, ensure_ascii=False) + ";\n")
    print(f"{len(builds)} builds, {len(src['selected'])} selected, {sum(1 for b in builds if b['thumb'])} with a preview image")
    return 0


if __name__ == "__main__":
    sys.exit(main())
